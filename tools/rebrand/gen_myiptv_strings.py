#!/usr/bin/env python3
"""Rebrand the user-visible OwnTV strings of the core library to MyIPTV.

The interface strings live in the OwnTV_Core library (26 languages), which this app consumes as a
published artifact, so they cannot be edited here. Android lets an app override a library resource
by defining the same name in its own res/, which is what this script generates: for every string,
plural or string-array of core that mentions "OwnTV", a copy with "MyIPTV" in app/src/main/res.

Usage (core checked out at the tag the app pins, see owntvCore in gradle/libs.versions.toml):

    git clone https://github.com/ahXN00/OwnTV_Core /tmp/core && git -C /tmp/core checkout core-1.0.69
    python3 tools/rebrand/gen_myiptv_strings.py --core /tmp/core/core/src/main/res --out app/src/main/res

Re-run it whenever owntvCore is bumped, so new strings come out rebranded too. Output files are
named strings_myiptv.xml and are fully regenerated each time.

Strings in KEEP_OWNTV name something that really belongs to the original project (its shared
metadata/subtitles service, its translation project) and keep the OwnTV name on purpose.
"""
import argparse
import glob
import os
import re
import sys

OLD, NEW = "OwnTV", "MyIPTV"
OUT_NAME = "strings_myiptv.xml"

KEEP_OWNTV = {
    "settings_metadata_shared_worker_description",   # "OwnTV Worker": the author's shared service
    "settings_open_subtitles_access_priority",        # "OwnTV's shared Worker"
    "settings_metadata_fair_share",                   # the shared service is used by all OwnTV users
    "settings_language_help_translate",               # the upstream translation project
    "settings_language_contribution_description",
    "settings_language_contribution_qr_description",
}

ELEMENT = re.compile(r'<(string|plurals|string-array)\b[^>]*?\bname="([^"]+)"[^>]*?>.*?</\1>', re.S)
HEADER = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tools/rebrand/gen_myiptv_strings.py from OwnTV_Core. Do not edit by hand. -->\n"
    '<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2" '
    'xmlns:tools="http://schemas.android.com/tools">\n'
)


def elements(res_dir):
    """name -> raw XML element, over every values file of one core values* directory."""
    found = {}
    for path in sorted(glob.glob(os.path.join(res_dir, "*.xml"))):
        text = open(path, encoding="utf-8").read()
        for m in ELEMENT.finditer(text):
            found[m.group(2)] = m.group(0)
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--core", required=True, help="core/src/main/res of OwnTV_Core")
    ap.add_argument("--out", required=True, help="app/src/main/res")
    args = ap.parse_args()

    locales = {os.path.basename(d): elements(d) for d in sorted(glob.glob(os.path.join(args.core, "values*")))
               if os.path.basename(d) == "values" or os.path.basename(d).startswith("values-")}
    default = locales.get("values")
    if not default:
        sys.exit("no values/ directory under --core")

    # Keys to override: every default or translated element that names the brand, minus the keep list.
    keys = {k for loc in locales.values() for k, raw in loc.items() if OLD in raw and k not in KEEP_OWNTV}
    keys = {k for k in keys if k in default}  # an override needs a default to hang its translations on

    # A name defined twice inside the app's own res would fail the build; refuse instead.
    own = set()
    for path in glob.glob(os.path.join(args.out, "values*", "*.xml")):
        if os.path.basename(path) == OUT_NAME:
            continue
        own |= set(re.findall(r'<(?:string|plurals|string-array)\b[^>]*\bname="([^"]+)"', open(path, encoding="utf-8").read()))
    clash = sorted(keys & own)
    if clash:
        sys.exit("already defined in the app's own res: " + ", ".join(clash))

    written = 0
    for loc_name, loc in locales.items():
        entries = [loc[k].replace(OLD, NEW) for k in sorted(keys) if k in loc]
        target = os.path.join(args.out, loc_name, OUT_NAME)
        if not entries:
            if os.path.exists(target):
                os.remove(target)
            continue
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(HEADER)
            for e in entries:
                f.write("    " + e + "\n")
            f.write("</resources>\n")
        written += 1
        print(f"{loc_name:16} {len(entries):3} strings")
    print(f"{len(keys)} keys, {written} files, kept as OwnTV: {len(KEEP_OWNTV)}")


if __name__ == "__main__":
    main()
